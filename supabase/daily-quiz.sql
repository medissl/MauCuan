create table public.daily_quizzes (
  user_id uuid not null references public.profiles(id) on delete cascade,
  day date not null,
  question_ids text[] not null check(cardinality(question_ids)=5),
  answers smallint[] not null default '{}' check(cardinality(answers)<=5),
  completed boolean not null default false,
  reward smallint not null default 0 check(reward in (0,5)),
  primary key(user_id,day),
  constraint quiz_completion_check check(completed=(cardinality(answers)=5) and reward=case when completed then 5 else 0 end)
);
alter table public.daily_quizzes enable row level security;
revoke all on public.daily_quizzes from public,anon,authenticated;
grant select on public.daily_quizzes to authenticated;
create policy quizzes_owner_read on public.daily_quizzes for select to authenticated using(user_id=(select auth.uid()));
create function private.daily_quiz(p_question text default null,p_answer integer default null,p_day date default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare uid uuid:=auth.uid(); today date:=(now() at time zone 'Asia/Jakarta')::date;
  s public.daily_quizzes; ids text[]; correct_answer integer; old_index integer;
begin
  if uid is null then raise exception 'Authentication required'; end if;
  perform 1 from public.profiles where id=uid for update;
  if not found then raise exception 'Profil belum tersedia'; end if;
  if p_day is not null and p_day<>today then raise exception 'Hari sudah berganti. Buka kuis hari ini lagi.'; end if;
  select * into s from public.daily_quizzes where user_id=uid and day=today;
  if not found then
    if p_question is not null then raise exception 'Buka kuis dahulu'; end if;
    if not exists(select 1 from public.daily_quizzes where user_id=uid) then
      ids:=array['q001','q002','q003','q004','q005'];
    else
      select array_agg(id) into ids from (
        select b.id from private.quiz_bank b
        where not exists(select 1 from public.daily_quizzes q where q.user_id=uid and q.day>=today-7 and b.id=any(q.question_ids))
        order by exists(select 1 from public.daily_quizzes q where q.user_id=uid and b.id=any(q.question_ids)),random() limit 5
      ) candidate;
    end if;
    if cardinality(ids)<>5 then raise exception 'Kuis belum tersedia'; end if;
    insert into public.daily_quizzes(user_id,day,question_ids) values(uid,today,ids) returning * into s;
  end if;
  if p_question is not null then
    if p_answer is null or p_answer not between 0 and 2 then raise exception 'Pilih jawaban yang tersedia'; end if;
    old_index:=array_position(s.question_ids,p_question);
    if old_index is null then raise exception 'Soal bukan bagian kuis hari ini'; end if;
    if old_index>cardinality(s.answers) then
      if s.completed or old_index<>cardinality(s.answers)+1 then raise exception 'Jawab soal secara berurutan'; end if;
      s.answers:=array_append(s.answers,p_answer::smallint);
      s.completed:=cardinality(s.answers)=5;
      s.reward:=case when s.completed then 5 else 0 end;
      update public.daily_quizzes set answers=s.answers,completed=s.completed,reward=s.reward where user_id=uid and day=today;
    end if;
    -- A retry for the same question returns the stored answer without advancing.
    select correct into correct_answer from private.quiz_bank where id=p_question;
  end if;
  return jsonb_build_object('day',s.day,'question_ids',s.question_ids,'answers',s.answers,'completed',s.completed,'reward',s.reward,'correct',correct_answer);
end $$;
revoke all on function private.daily_quiz(text,integer,date) from public,anon,authenticated;
grant execute on function private.daily_quiz(text,integer,date) to authenticated;
create function public.daily_quiz(p_question text default null,p_answer integer default null,p_day date default null)
returns jsonb language sql security invoker set search_path='' as $$select private.daily_quiz(p_question,p_answer,p_day)$$;
revoke all on function public.daily_quiz(text,integer,date) from public,anon,authenticated;
grant execute on function public.daily_quiz(text,integer,date) to authenticated;

